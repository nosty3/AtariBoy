#!/usr/bin/env python3
"""Build user's 128 x 8-byte Atari font into 2-bpp OSD glyphs.
Pixel codes: 00 black outline, 01 transparent, 11 white ink.
The outline is computed here, never on RP2040 during emulation.
"""
from pathlib import Path
r=Path(__file__).resolve().parents[1]
source=(r/'assets/atari-font.fnt').read_bytes()
assert len(source)==128*8
out=bytearray()
for glyph in range(128):
 rows=source[glyph*8:glyph*8+8]
 def ink(x,y):return 0<=x<8 and 0<=y<8 and bool(rows[y]&(128>>x))
 for y in range(8):
  colors=[3 if ink(x,y) else 0 if any(ink(x+dx,y+dy) for dx in (-1,0,1) for dy in (-1,0,1)) else 1 for x in range(8)]
  out.extend(sum(colors[x+i]<<(6-i*2) for i in range(4)) for x in (0,4))
assert len(out)==2048
(r/'generated').mkdir(exist_ok=True)
(r/'generated/osd-font-2bpp.bin').write_bytes(out)
(r/'generated/osd_font.hpp').write_text('// Generated by build_font.py from assets/atari-font.fnt.\n#pragma once\n#include <stdint.h>\nnamespace osd {\ninline constexpr uint8_t font[128][16] = {\n'+''.join('{'+','.join(f'0x{v:02x}' for v in out[i:i+16])+'},\n' for i in range(0,len(out),16))+'};\n}\n')
print('OSD font: 128 glyphs, 2048 bytes, precomputed outlines and transparency')
