#!/usr/bin/env python3
"""PCM loops: PAL/SECAM 312 lines or NTSC 262; input work in blanking.
Values are prepared before WSYNC. DMA can still delay opcode fetches.
"""
from pathlib import Path
import sys
ntsc='--ntsc' in sys.argv
r=Path(__file__).resolve().parents[1]
out=['''; Generated by build_audio_atari.py. ZP F2=audio enable, F3=sample index, F4=temporary; F0/F1 reserved.
        org $3000
audiostart
        lda #0
        sta $d40e
        sta $f0
        sta $f2
        lda #$b8
        sta $f1
        lda #0
        sta $d208
        sta $d218
        lda #$18
        sta $d211
        sta $d213
        lda #$17
        sta $d215
        sta $d217
waitlast lda $d40b
        cmp #LAST_VCOUNT
        bne waitlast
waitzero lda $d40b
        bne waitzero
        ldy #0
        sty $f3
audioframe
        lda $a13f
        sta $f2
''']
# First six lines remain in top border; menu/game display setup split into
# bounded pieces. Sample count never depends on the amount of input work.
pre=[
'lda $a000\nsta displaymode',
'ldx displaymode\nlda displaylo,x\nsta $d402',
'ldx displaymode\nlda displayhi,x\nsta $d403',
'lda $a001\nsta $d01a\nlda $a002\nsta $d016',
'lda $a003\nsta $d017\nlda $a004\nsta $d018',
'ldx $a005\nlda audioentrylo,x\nsta audiojump+1\nlda audioentryhi,x\nsta audiojump+2'
]
def sample(name,hi):
 shift=0 if hi==0xb8 else 256
 return f"""{name}
        lda $f2
        beq {name}silent
        lda ${0xbd00+shift:04x},y
        tax
        lda ${0xbe40+shift:04x},y
        sta $f4
        lda ${0xbb00+shift:04x},y
        ldy $f4
        jmp {name}write
{name}silent
        lda #$18
        ldx #$17
        ldy #$17
{name}write
        sta $d40a
        sta $d201
        sta $d203
        stx $d205
        sty $d207
        ldy $f3
        iny
        sty $f3
"""
tasks=[
'lda $d300\nsta packet+15\nand #15\nsta packet',
'lda packet+15\nlsr\nlsr\nlsr\nlsr\nsta packet+4',
'lda $d010\nand #1\nsta packet+1',
'lda $d011\nand #1\nsta packet+5',
]
for i,target in enumerate([2,3,6,7,18,19,20,21]):
 tasks.append(f'lda potwarm\nbeq audpot{i}\nlda #228\nbne audputpot{i}\naudpot{i} lda ${0xd200+i:04x}\naudputpot{i} sta packet+{target}')
tasks += [
'lda potwarm\nbeq audwarmdone\ndec potwarm\naudwarmdone',
'lda $d20f\nsta packet+16\nlda $d209\nsta packet+17',
'lda packet+16\nand #4\nbne audnokey\nlda packet+17\nand #$3f\njmp audgotkey\naudnokey lda #$ff\naudgotkey sta packet+10',
'lda packet+10\ncmp prevkey\nbeq audsame\nsta prevkey\ncmp #$ff\nbeq audsame\nsta lastkey\ninc keyseq\naudsame',
'lda lastkey\nsta packet+8\nlda keyseq\nsta packet+9',
'lda #0\nsta packet+11\nlda packet+10\ncmp #$11\nbne audnohelp\ninc packet+11\naudnohelp',
'lda $d01f\neor #7\nand #7\nsta temp\nand #1\nsta packet+12',
'lda temp\nlsr\nand #1\nsta packet+13',
'lda temp\nlsr\nlsr\nand #1\nsta packet+14',
'lda #0\nsta packet+22\nsta $d20b',
'inc frame\nlda frame\nsta packet+23',
]
tasks.append('lda $a160\nbeq audnoturbo\njmp turboaudiopause\naudnoturbo')
assert len(tasks)<=40
# NTSC has 50 fewer lines. Keep all input work outside the 216-line mode D
# playfield. Start slow POT scan at the top; read it after >=228 lines.
# Final packet byte is ALWAYS committed on the final scanline.
if ntsc:
 schedule={i:pre[i] for i in range(6)}
 schedule[6]=tasks[21] # POTGO: completion before POT reads on lines 240..247
 schedule.update({7+i:tasks[i] for i in range(4)})
 groups=[[13],[14],[15],[16,17],[18],[19,20],[22,23]]
 schedule.update({11+i:'\n'.join(tasks[j] for j in group) for i,group in enumerate(groups)})
 schedule.update({240+i:tasks[4+i] for i in range(8)})
 schedule[248]=tasks[12]
 for i in range(11):
  schedule[249+i]='\n'.join(f'lda packet+{j}\nsta ${0xa120+j:04x}' for j in [i*2,i*2+1])
 schedule[260]='lda packet+22\nsta $a136'
 schedule[261]='lda packet+23\nsta $a137'
else:
 schedule={i:pre[i] for i in range(6)}
 schedule.update({248+i:t for i,t in enumerate(tasks)})
 schedule.update({288+i:f'lda packet+{i}\nsta ${0xa120+i:04x}' for i in range(24)})
head=18 if ntsc else 6
tail=240 if ntsc else 248
lines=262 if ntsc else 312
for i in range(head):
 out+=['        jsr audiosample\n',schedule.get(i,'')+'\n']
out += [f'''        lda displaymode
        bne audactive
audquiet
        sta $d40a
        iny
        cpy #{tail}
        bne audquiet
        sty $f3
        jmp audtail
''',sample('audactive',0xb8),f'        cpy #{tail}\n        bne audactive\naudtail\n']
for i in range(tail,lines):
 out.append('        jsr '+('audiosample' if i<256 else 'audiosamplehi')+'\n')
 out.append(schedule.get(i,'')+'\n')
out+=['''        ldy #0
        sty $f3
        ldx $a000
        lda displayui,x
        bne audoptions
audiojump jmp audioframe
audoptions
        jmp optionsstart
''',sample('audiosample',0xb8),'        rts\n',sample('audiosamplehi',0xb9),'        rts\naudioentrylo dta <audioframe,<stereoframe\naudioentryhi dta >audioframe,>stereoframe\n        ert *>$4000\n']
s=''.join(out)
s='\n'.join(('        '+line if line.split() and line.split()[0] in {'ldx','lda','sta','and','tax','lsr','beq','bne','jmp','inc','dec','cmp','eor','rts'} else line) for line in s.splitlines())+'\n'
(r/'generated/audio_player.asm').write_text(s)

# Fixed-address unrolled stereo loop: no indexed reads or loop counter during DMA.
# 6 LDA abs + 8 STA abs + STA WSYNC = 60 CPU cycles / active line.
def right_address(i):
 for base,size in [(0xb000,512),(0xa008,248),(0xbf78,136),(0xafe8,24),(0xba98,16)]:
  if i<size:return base+i
  i-=size
 raise ValueError(i)
st=['        org $5000\nstereoframe\n        lda $a13f\n        sta $f2\n        bne stereoplay\n        jmp stereoquiet\n']
for quiet in [False,True]:
 st.append(('stereoquiet' if quiet else 'stereoplay')+'\n')
 for i in range(lines):
  st.append('        sta $d40a\n')
  # Transition work belongs AFTER the first WSYNC, in the new line budget.
  # Before it, the final audible sample + commit already use most of a line.
  if quiet and i==0:
   st.append('        lda #$18\n')
   for addr in [0xd201,0xd203,0xd211,0xd213]:st.append(f'        sta ${addr:04x}\n')
   st.append('        lda #$17\n')
   for addr in [0xd205,0xd207,0xd215,0xd217]:st.append(f'        sta ${addr:04x}\n')
  if not quiet:
   for src,dst in [(0xbb00+i,[0xd201,0xd203]),(0xbd00+i,[0xd205]),(0xbe40+i,[0xd207]),(right_address(i),[0xd211,0xd213]),(right_address(312+i),[0xd215]),(right_address(624+i),[0xd217])]:
    st.append(f'        lda ${src:04x}\n')
    for a in dst:st.append(f'        sta ${a:04x}\n')
  if i in schedule:st.append(schedule[i]+'\n')
  # Menu resumes mono loop at the SAME index; top input work already done.
  if i==head-1:st.append('        lda displaymode\n        bne '+('sqgame' if quiet else 'spgame')+'\n        jmp stereomenu\n'+('sqgame' if quiet else 'spgame')+'\n')
 # Last sample is followed by 24th input commit; UI dispatch occurs before WSYNC.
 st.append('        ldx $a000\n        lda displayui,x\n        beq '+('sqnext' if quiet else 'spnext')+'\n        jmp optionsstart\n'+('sqnext' if quiet else 'spnext')+' jmp audiojump\n')
 # Task labels must be unique in three copies (mono, stereo, silent stereo).
# Prefix only task labels, leaving shared variables and entry points untouched.
st.append(f'stereomenu\n        sta $d40a\n        lda #$18\n        sta $d211\n        sta $d213\n        lda #$17\n        sta $d215\n        sta $d217\n        ldy #{head+1}\n        sty $f3\n        jmp audquiet\n')
st=''.join(st)
import re
# Labels can follow instructions in source task strings; all definitions use these prefixes.
labels=re.findall(r'(aud(?:pot\d+|putpot\d+|warmdone|nokey|gotkey|same|nohelp|noturbo))', '\n'.join(tasks))
# Rename labels independently for each emitted frame variant.
cut=st.index('stereoquiet\n        sta $d40a')
normal,silent=st[:cut],st[cut:]
for label in set(labels):
 normal=re.sub(r'\b'+label+r'\b','st_'+label,normal)
 silent=re.sub(r'\b'+label+r'\b','sq_'+label,silent)
st=normal+silent
ops={'ldx','lda','sta','and','tax','lsr','beq','bne','jmp','inc','dec','cmp','eor','rts'}
st='\n'.join(('        '+line if line.split() and line.split()[0] in ops else line) for line in st.splitlines())+'\n        ert *>$a000\n'
(r/'generated/stereo_player.asm').write_text(st)
